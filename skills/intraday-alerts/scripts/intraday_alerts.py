#!/usr/bin/env python3
"""intraday-alerts: price alerts and the NYSE clock for an open day trade.

    python3 intraday_alerts.py clock                          # is the NYSE open? next open / close
    python3 intraday_alerts.py quote TSLA --write             # quotes -> state/intraday/prices.json
    python3 intraday_alerts.py quote --holdings --write       # every ticker in your portfolio and plan
    python3 intraday_alerts.py add --from-plan                # stop, target and flat-by-close from the newest exit plan
    python3 intraday_alerts.py add --symbol TSLA --stop 358.32
    python3 intraday_alerts.py add --symbol TSLA --target 370.04
    python3 intraday_alerts.py add --at 15:55 --label "flat by close" --before-close
    python3 intraday_alerts.py add --symbol KO --pct 3
    python3 intraday_alerts.py add --opening-bell
    python3 intraday_alerts.py check                          # rings what hit, once; exit 1 if nothing rang
    python3 intraday_alerts.py check --now "2026-10-19 15:55" --offline scripts/tests/fixtures
    python3 intraday_alerts.py list
    python3 intraday_alerts.py reset tsla-plan-stop

Rule types:
  above / target  the price is at or above "price"
  below / stop    the price is at or below "price"
  pct_move        the price moved "pct" percent or more from the previous close
                  (or from "ref" if you give one); "direction": "up" or "down"
  opening_bell    the NYSE opened today (rings once per trading day)
  time            the New York clock passed "at" (HH:MM) on a trading day
                  (rings once per trading day); "before_close": true moves it
                  earlier with an early close (3 hours before a 1:00 p.m. close), so a 15:55
                  "flat by close" rings at 12:55 on those days

A rule with "date" is only watched on that New York date (rules from a plan
are for the plan's day only). An above / below alert rings ONCE and then stays
quiet until you reset it, unless the rule has "rearm": true (it re-arms when
the price crosses back). A pct_move alert rings at most once per day.

Quotes (free, delayed, unofficial; for alerts only, never for timing an order):
  yahoo   https://query2.finance.yahoo.com/v8/finance/chart/TSLA (falls back to
          query1 on a 429 or a 5xx; one retry with a pause on a 429; one
          request per ticker, half a second apart; the default)
  stooq   https://stooq.com/q/l/?s=tsla.us&f=sd2t2ohlcv&h&e=csv (Stooq's free
          CSV; it answered 404 on 2026-10-13, kept for when it is back)
  --offline DIR reads DIR/<source>-<TICKER>.json|csv (or .json.gz) instead.

NYSE calendar: holidays and early closes come from the repository's shared
XNYS calendar (_market_calendar.py, pandas-market-calendars).

State lives in state/intraday/: alerts.json (the rules), alerts_state.json
(what rang) and prices.json (the last quotes).
"""

