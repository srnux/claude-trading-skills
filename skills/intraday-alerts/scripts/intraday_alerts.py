def stooq_url(sym):
    return "https://stooq.com/q/l/?s={}.us&f=sd2t2ohlcv&h&e=csv".format(
        sym.lower().replace(".", "-")
    )


def yahoo_url(sym, host=YAHOO_HOSTS[0]):
    return "https://{}/v8/finance/chart/{}?range=1d&interval=1d".format(
        host, sym.upper().replace(".", "-")
    )


def parse_stooq(text, sym):
    """Symbol,Date,Time,Open,High,Low,Close,Volume -> quote. N/D means no data."""
    rows = list(csv.DictReader(io.StringIO(text.strip())))
    if not rows:
        raise AlertError(f"Stooq returned no rows for {sym}")
    r = {k.strip().lower(): (v or "").strip() for k, v in rows[0].items() if k}
    close = r.get("close", "")
    if not close or close.upper() == "N/D":
        raise AlertError(f"Stooq has no data for {sym} (check the ticker)")

    def f(k):
        v = r.get(k, "")
        try:
            return float(v)
        except ValueError:
            return None

    return {
        "symbol": sym.upper(),
        "price": float(close),
        "open": f("open"),
        "high": f("high"),
        "low": f("low"),
        "prev_close": None,
        "time": ("{} {}".format(r.get("date", ""), r.get("time", ""))).strip(),
        "source": "stooq",
    }


def parse_yahoo(text, sym):
    try:
        data = json.loads(text)
        res = data["chart"]["result"]
    except (ValueError, KeyError, TypeError):
        raise AlertError(f"Yahoo returned something unexpected for {sym}")
    if not res:
        err = (data.get("chart") or {}).get("error") or {}
        raise AlertError(
            "Yahoo has no data for {}: {}".format(sym, err.get("description", "unknown ticker"))
        )
    m = res[0].get("meta", {})
    price = m.get("regularMarketPrice")
    if price is None:
        raise AlertError(f"Yahoo has no price for {sym}")
    t = m.get("regularMarketTime")
    when = (
        datetime.datetime.fromtimestamp(t, datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
        if t
        else ""
    )
    q = (res[0].get("indicators", {}).get("quote") or [{}])[0]
    opens = [x for x in (q.get("open") or []) if x is not None]
    return {
        "symbol": sym.upper(),
        "price": float(price),
        "open": opens[0] if opens else None,
        "high": m.get("regularMarketDayHigh"),
        "low": m.get("regularMarketDayLow"),
        "prev_close": m.get("previousClose") or m.get("chartPreviousClose"),
        "time": when,
        "currency": m.get("currency"),
        "source": "yahoo",
    }


_urlopen = urllib.request.urlopen  # tests swap these two
_sleep = time.sleep


def _get(url, timeout=20):
    """(HTTP status, body). A network failure is an AlertError."""
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "*/*"})
    try:
        with _urlopen(req, timeout=timeout) as r:
            return 200, r.read().decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        try:
            body = e.read().decode("utf-8", "replace")
        except Exception:
            body = ""
        finally:
            try:
                e.close()
            except Exception:
                pass
        return e.code, body
    except urllib.error.URLError as e:
        raise AlertError("could not reach {}: {}".format(url.split("/")[2], e.reason))


def fetch(url, timeout=20):
    code, text = _get(url, timeout)
    if code != 200:
        raise AlertError("{} answered HTTP {:d}".format(url.split("?")[0], code))
    return text


def fetch_yahoo(sym, timeout=20):
    """query2 first. A 429 waits BACKOFF seconds and tries once more; a 429 or a 5xx
    after that moves on to query1. A 404 comes back as Yahoo's own error JSON."""
    last = None
    for host in YAHOO_HOSTS:
        url = yahoo_url(sym, host)
        code, text = _get(url, timeout)
        if code == 429:
            _sleep(BACKOFF)
            code, text = _get(url, timeout)
        if code == 200:
            return text
        if code == 404 and text.strip().startswith("{"):
            return text
        last = (url, code)
        if code != 429 and code < 500:
            break
    raise AlertError("{} answered HTTP {:d}".format(last[0].split("?")[0], last[1]))


def _offline_text(folder, source, sym):
    ext = "csv" if source == "stooq" else "json"
    base = os.path.join(folder, f"{source}-{sym}.{ext}")
    if os.path.exists(base):
        with open(base, encoding="utf-8") as fh:
            return fh.read()
    if os.path.exists(base + ".gz"):
        with gzip.open(base + ".gz", "rt", encoding="utf-8") as fh:
            return fh.read()
    raise AlertError(f"no offline quote file {base}")


def get_quotes(symbols, source="yahoo", offline=None, pause=PAUSE):
    """{SYM: quote} and [errors]. One request per ticker, with a pause between."""
    quotes, errors = {}, []
    for i, sym in enumerate(symbols):
        sym = sym.upper()
        try:
            if offline:
                text = _offline_text(offline, source, sym)
            else:
                if i and pause:
                    _sleep(pause)
                text = fetch(stooq_url(sym)) if source == "stooq" else fetch_yahoo(sym)
            quotes[sym] = parse_stooq(text, sym) if source == "stooq" else parse_yahoo(text, sym)
        except AlertError as e:
            errors.append(str(e))
    return quotes, errors


def write_prices(path, quotes, now_utc, source):
    old = {}
    if os.path.exists(path):
        try:
            with open(path, encoding="utf-8") as fh:
                old = json.load(fh)
        except (ValueError, OSError):
            old = {}
    prices = dict(old.get("prices", {}))
    detail = dict(old.get("detail", {}))
    stamp = now_utc.strftime("%Y-%m-%dT%H:%M:%SZ")
    for s, q in quotes.items():
        prices[s] = q["price"]
        detail[s] = {
            "prev_close": q.get("prev_close"),
            "time": q.get("time"),
            "source": q.get("source"),
            "fetched": stamp,
        }
    doc = {
        "as_of": stamp,
        "source": source,
        "note": (
            "Delayed quotes for alerts and sizing checks. Your broker's price is the one that fills. "
            "detail.fetched is when each price was read."
        ),
        "prices": prices,
        "detail": detail,
    }
    _write(path, doc)
    return doc


def _write(path, doc):
    d = os.path.dirname(path)
    if d:
        os.makedirs(d, exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=2)
        fh.write("\n")
    os.replace(tmp, path)


def latest_report(output_dir, prefix):
    """The newest <output_dir>/<prefix>*.json by modification time, or None."""
    paths = [p for p in glob.glob(os.path.join(output_dir, prefix + "*.json")) if os.path.isfile(p)]
    return max(paths, key=os.path.getmtime) if paths else None


def _read(path, default):
    if not path or not os.path.exists(path):
        return default
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except ValueError as e:
        raise AlertError(f"{path} is not valid JSON: {e}")


# ---------------------------------------------------------------- rules

PRICE_TYPES = {"above", "below", "stop", "target", "pct_move", "opening_bell", "time"}
NO_QUOTE = {"opening_bell", "time"}


def _hhmm(text):
    m = HHMM.match(str(text or "").strip())
    if not m:
        return None
    return datetime.time(int(m.group(1)), int(m.group(2)))


def validate(rule):
    t = rule.get("type")
    if t not in PRICE_TYPES:
        raise AlertError("rule {}: unknown type {!r}".format(rule.get("id"), t))
    if t not in NO_QUOTE and not rule.get("symbol"):
        raise AlertError("rule {} needs a symbol".format(rule.get("id")))
    if t in ("above", "below", "stop", "target") and not isinstance(
        rule.get("price"), (int, float)
    ):
        raise AlertError("rule {} needs a numeric price".format(rule.get("id")))
    if t == "pct_move" and not isinstance(rule.get("pct"), (int, float)):
        raise AlertError("rule {} needs a numeric pct".format(rule.get("id")))
    if t == "time" and _hhmm(rule.get("at")) is None:
        raise AlertError(
            'rule {} needs "at" as a New York time like "15:55"'.format(rule.get("id"))
        )
    if rule.get("date") and not re.match(r"^\d{4}-\d{2}-\d{2}$", str(rule["date"])):
        raise AlertError("rule {}: date must be YYYY-MM-DD".format(rule.get("id")))


def active(rule, today):
    """A rule with a "date" is watched on that New York date only."""
    return not rule.get("date") or str(rule["date"]) == today


def _rang_today(stamp, today):
    """Did a rule that rang at this UTC stamp ring on this New York date?"""
    if not stamp:
        return False
    try:
        utc = datetime.datetime.strptime(stamp[:19], "%Y-%m-%dT%H:%M:%S")
    except ValueError:
        return stamp[:10] == today
    return to_eastern(utc).date().isoformat() == today


def ring_time(rule, status):
    """The time a time rule rings today. With "before_close" it moves up with an early close
    by as much as the close moved (a 15:55 "flat by close" rings at 12:55 before a 1:00 p.m. close)."""
    at = _hhmm(rule.get("at"))
    closes = _hhmm(status.get("closes") or "")
    if rule.get("before_close") and status.get("early_close") and closes:
        base = datetime.date(2000, 1, 1)
        shift = datetime.datetime.combine(base, CLOSE) - datetime.datetime.combine(base, closes)
        at = (datetime.datetime.combine(base, at) - shift).time()
    return at


def evaluate(rules, quotes, status, state, now_utc):
    """Pure function. Returns (rings, new_state). Each ring: {id, symbol, message}."""
    state = json.loads(json.dumps(state or {}))
    rung = state.setdefault("rung", {})
    today = status["date"]
    local = to_eastern(now_utc)
    stamp = now_utc.strftime("%Y-%m-%dT%H:%M:%SZ")
    rings = []
    for r in rules:
        validate(r)
        rid = r.get("id") or "{}-{}".format(r.get("symbol", "market"), r["type"])
        if not active(r, today):
            continue
        typ = {"stop": "below", "target": "above"}.get(r["type"], r["type"])
        if typ == "opening_bell":
            if status["open"] and not _rang_today(rung.get(rid), today):
                rings.append(
                    {
                        "id": rid,
                        "symbol": "",
                        "message": "Opening bell: the NYSE is open ({} New York){}.".format(
                            status["now_new_york"],
                            (", " + status["early_close"] + " today")
                            if status.get("early_close")
                            else "",
                        ),
                    }
                )
                rung[rid] = stamp
            continue
        if typ == "time":
            at = ring_time(r, status)
            if status.get("opens") and local.time() >= at and not _rang_today(rung.get(rid), today):
                label = r.get("label") or "time alert"
                msg = "{}{}: it is {} New York (set for {})".format(
                    label[:1].upper(), label[1:], local.strftime("%H:%M"), at.strftime("%H:%M")
                )
                msg += (
                    (", the market closes at {}.".format(status["closes"]))
                    if status["open"]
                    else ", the market has closed."
                )
                sym = str(r.get("symbol") or "").upper()
                if sym:
                    msg += (
                        f" If {sym} is still open, close it: review the position with portfolio-manager and "
                        "send the sell yourself after pre-trade-discipline-gate."
                    )
                rings.append({"id": rid, "symbol": sym, "message": msg})
                rung[rid] = stamp
            continue
        sym = r["symbol"].upper()
        q = quotes.get(sym)
        if not q:
            continue
        p = q["price"]
        if typ in ("above", "below"):
            hit = p >= r["price"] if typ == "above" else p <= r["price"]
            if hit and rid not in rung:
                word = "at or above" if typ == "above" else "at or below"
                label = {"stop": "stop", "target": "target"}.get(r["type"], "alert level")
                rings.append(
                    {
                        "id": rid,
                        "symbol": sym,
                        "message": "{} {} ${:.2f}: {} your {} ${}{}.".format(
                            sym,
                            "is" if status["open"] else "last",
                            p,
                            word,
                            label,
                            _n(r["price"]),
                            (" (" + r["note"] + ")") if r.get("note") else "",
                        ),
                    }
                )
                rung[rid] = stamp
            elif not hit and rid in rung and r.get("rearm"):
                del rung[rid]
        elif typ == "pct_move":
            ref = r.get("ref") or q.get("prev_close") or q.get("open")
            if not ref:
                continue
            move = 100.0 * (p / float(ref) - 1)
            want = r.get("direction")
            hit = abs(move) >= r["pct"] and (not want or (want == "up") == (move > 0))
            if hit and not _rang_today(rung.get(rid), today):
                rings.append(
                    {
                        "id": rid,
                        "symbol": sym,
                        "message": f"{sym} moved {move:+.2f}% to ${p:.2f} (from ${float(ref):.2f}).",
                    }
                )
                rung[rid] = stamp
    state["last_check"] = stamp
    return rings, state


def _n(x):
    x = float(x)
    return str(int(x)) if x == int(x) else f"{x:.2f}"


def rules_from_plan(plan, cfg_flat_by=None):
    """An intraday-exit-planner plan -> a stop alert, a target alert and a flat-by-close time alert, for the plan's day."""
    if not isinstance(plan, dict) or not plan.get("symbol"):
        raise AlertError("the plan has no symbol (run intraday-exit-planner first)")
    sym = str(plan["symbol"]).upper()
    out = []
    for key, typ, word in (("stop", "stop", "plan stop"), ("target", "target", "plan target")):
        v = plan.get(key)
        if not isinstance(v, (int, float)) or v <= 0:
            raise AlertError(f"the plan has no {key} (run intraday-exit-planner)")
        label = plan.get(f"{key}_label")
        out.append(
            {
                "id": f"{sym.lower()}-plan-{key}",
                "symbol": sym,
                "type": typ,
                "price": float(v),
                "note": word + (": " + label if label else ""),
            }
        )
    flat = plan.get("flat_by") or cfg_flat_by or "15:55"
    if _hhmm(flat) is None:
        raise AlertError(f"the plan's flat_by {flat!r} is not a time like 15:55")
    out.append(
        {
            "id": f"{sym.lower()}-flat-by",
            "symbol": sym,
            "type": "time",
            "at": flat,
            "label": "flat by close",
            "before_close": True,
        }
    )
    if plan.get("date"):
        for r in out:
            r["date"] = str(plan["date"])
    return out


