INTERVALS = {"1m": 60, "5m": 300}
DEFAULTS = {"flat_by": "15:55", "min_reward_risk": 1.0}
DEFAULT_OUTPUT_DIR = "reports/"
ATR_BARS = 14
MIN_RISK_PCT = Decimal("0.05")  # risk under 0.05% of the price is inside the spread's noise
CENT = Decimal("0.01")
EPOCH = datetime.datetime(1970, 1, 1)
NOTE = "A stop is a plan, not a guarantee: a gap or a fast market can fill past it."

OPEN = datetime.time(9, 30)
CLOSE = datetime.time(16, 0)


class PlanError(Exception):
    pass


# The NYSE session comes from the repository's shared cash-equity calendar
# (_market_calendar.py, generated by scripts/generate_market_calendar.py), so
# holidays and 1:00 p.m. early closes never go stale.


class CalendarMissing(Exception):
    """The shared NYSE calendar could not be loaded (exit code 2)."""


@functools.lru_cache(maxsize=1024)
def _nyse_session(iso_day):
    try:
        s = _market_calendar.session_for_date("XNYS", datetime.date.fromisoformat(iso_day))
    except _market_calendar.CalendarUnavailableError as e:
        raise CalendarMissing(
            f"the NYSE calendar is unavailable ({e}). Install the skill's requirements.txt"
        )
    if s is None:
        return None
    return s.market_open.time(), s.market_close.time()


def trading_day(d):
    """(is_trading_day, reason). Weekends and NYSE holidays."""
    if d.weekday() >= 5:
        return False, "weekend"
    if _nyse_session(d.isoformat()) is None:
        return False, "NYSE holiday"
    return True, ""


def session(d):
    """(open_time, close_time) in New York time, or None if closed all day."""
    if d.weekday() >= 5:
        return None
    return _nyse_session(d.isoformat())


def early_close(d):
    """'1:00 p.m. early close' when the NYSE closes before 4:00 p.m. that day, else None."""
    s = session(d)
    if s and s[1] < CLOSE:
        h = s[1].hour % 12 or 12
        return f"{h:d}:{s[1].minute:02d} p.m. early close"
    return None


# ---------------------------------------------------------------- time


def _nth_sunday(year, month, n):
    d = datetime.date(year, month, 1)
    d += datetime.timedelta(days=(6 - d.weekday()) % 7)
    return d + datetime.timedelta(weeks=n - 1)


def eastern_offset(utc):
    """Hours from UTC for New York: -4 in daylight time, -5 otherwise (US rule since 2007)."""
    y = utc.year
    start = datetime.datetime.combine(_nth_sunday(y, 3, 2), datetime.time(7, 0))  # 2:00 EST
    end = datetime.datetime.combine(_nth_sunday(y, 11, 1), datetime.time(6, 0))  # 2:00 EDT
    naive = utc.replace(tzinfo=None)
    return -4 if start <= naive < end else -5


def to_eastern(utc):
    return utc.replace(tzinfo=None) + datetime.timedelta(hours=eastern_offset(utc))


def eastern_to_utc(local):
    for off in (-4, -5):
        utc = local - datetime.timedelta(hours=off)
        if eastern_offset(utc) == off:
            return utc
    return local + datetime.timedelta(hours=5)


def utc_now():
    return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0, tzinfo=None)


def utc_of(ts):
    return EPOCH + datetime.timedelta(seconds=int(ts))


def parse_now(text):
    """--now -> naive UTC. A time without an offset is New York time."""
    if not text:
        return utc_now()
    t = text.strip()
    if t.upper().endswith(" ET"):
        t = t[:-3].strip()
    if re.match(r"^\d{1,2}:\d{2}$", t):
        t = f"{to_eastern(utc_now()).date().isoformat()} {t.zfill(5)}"
    t = t.replace("Z", "+00:00")
    try:
        dt = datetime.datetime.fromisoformat(t)
    except ValueError:
        raise PlanError('--now wants a New York time like "2026-10-19 10:15" (or ...Z for UTC)')
    if dt.tzinfo is None:
        return eastern_to_utc(dt)
    return (dt - dt.utcoffset()).replace(tzinfo=None)


def parse_hhmm(text, what):
    m = re.match(r"^\s*(\d{1,2}):(\d{2})\s*$", str(text))
    if not m or int(m.group(1)) > 23 or int(m.group(2)) > 59:
        raise PlanError(f"{what} wants a New York time like 15:55, not {text!r}")
    return datetime.time(int(m.group(1)), int(m.group(2)))


def parse_clock(text, what):
    """10:15 AM, 10:15, 3:05 PM -> time."""
    m = re.match(r"^\s*(\d{1,2}):(\d{2})\s*([AaPp][Mm])?\s*$", str(text))
    if not m:
        raise PlanError(f"{what} wants a time like 10:15 AM, not {text!r}")
    h, mi = int(m.group(1)), int(m.group(2))
    if m.group(3):
        if not 1 <= h <= 12:
            raise PlanError(f"{what} wants a time like 10:15 AM, not {text!r}")
        h = h % 12 + (12 if m.group(3).upper() == "PM" else 0)
    if h > 23 or mi > 59:
        raise PlanError(f"{what} wants a time like 10:15 AM, not {text!r}")
    return datetime.time(h, mi)


def hm(t):
    return f"{t.hour:02d}:{t.minute:02d}"


def ampm(t):
    h = t.hour % 12 or 12
    return "{:d}:{:02d} {}".format(h, t.minute, "AM" if t.hour < 12 else "PM")


# ---------------------------------------------------------------- money math (Decimal, to the cent)


def D(x, what="a number"):
    try:
        if isinstance(x, float):
            return Decimal(repr(x))
        return Decimal(str(x).strip().lstrip("$").replace(",", ""))
    except (InvalidOperation, ValueError):
        raise PlanError(f"{what} is not a number: {x!r}")


def cents(x):
    """Round half up to the cent."""
    return D(x).quantize(CENT, rounding=ROUND_HALF_UP)


def floor_cents(x):
    """A long's stop: round down, away from the entry."""
    return D(x).quantize(CENT, rounding=ROUND_FLOOR)


def money(x):
    return "${}".format(format(D(x).quantize(CENT), ",f"))


def num(x):
    """1, 1.5, 2.25: a Decimal without trailing zeros."""
    s = format(D(x).normalize(), "f")
    return s


def ratio(x):
    """reward:risk for people: 1.0, 1.5, 1.37."""
    s = f"{float(x):.2f}"
    return s[:-1] if s.endswith("0") else s


WORDS = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five"}


def parse_stop(text):
    t = str(text).strip().lower()
    if t in ("or-mid", "or_mid", "mid", "or-midpoint"):
        return "or_mid", None
    if t in ("or-low", "or_low", "low"):
        return "or_low", None
    m = re.match(r"^(price|pct|atr):\s*\$?([0-9][0-9,]*\.?[0-9]*)$", t)
    if not m:
        raise PlanError(f"--stop is or-mid, or-low, price:X, pct:X or atr:K (got {text!r})")
    kind, val = m.group(1), D(m.group(2), "--stop")
    if val <= 0:
        raise PlanError(f"--stop {kind} needs a number above 0")
    if kind == "pct" and val >= 100:
        raise PlanError("--stop pct:X needs X under 100")
    return kind, val


def parse_target(text):
    t = str(text).strip()
    m = re.match(r"^([0-9]*\.?[0-9]+)\s*[Rr]$", t)
    if m:
        r = D(m.group(1), "--target")
        if r <= 0:
            raise PlanError("--target needs an R multiple above 0, like 1R or 2R")
        return "r", r
    m = re.match(r"^price:\s*\$?([0-9][0-9,]*\.?[0-9]*)$", t.lower())
    if m:
        return "price", D(m.group(1), "--target")
    raise PlanError(f"--target is 2R, 1R, 1.5R ... or price:X (got {text!r})")


def r_label(r):
    n = int(r) if r == r.to_integral_value() else None
    return f"{num(r)}R ({WORDS.get(n, num(r))} times the risk)"


def compute(
    entry,
    stop_rule,
    stop_param,
    target_rule,
    target_param,
    or_high=None,
    or_low=None,
    atr=None,
    atr_bars=None,
):
    """The stop, the target and the risk, in exact cents. Raises PlanError with the reason."""
    e = cents(entry)
    if e <= 0:
        raise PlanError("the entry price must be above $0")
    detail = ""
    if stop_rule in ("or_mid", "or_low"):
        if or_high is None or or_low is None:
            raise PlanError(
                "an {} stop needs the opening range (--or-high and --or-low)".format(
                    stop_rule.replace("_", "-")
                )
            )
        oh, ol = cents(or_high), cents(or_low)
        if oh <= ol:
            raise PlanError(f"the opening-range high {money(oh)} must be above its low {money(ol)}")
        if stop_rule == "or_mid":
            raw = (oh + ol) / 2
            label = "opening-range midpoint"
            detail = f"({money(oh)} + {money(ol)}) / 2 = ${num(raw)}"
        else:
            raw, label = ol, "opening-range low"
    elif stop_rule == "price":
        raw, label = stop_param, "your price"
    elif stop_rule == "pct":
        raw = e * (1 - stop_param / 100)
        label = f"{num(stop_param)}% under the entry"
        detail = f"{money(e)} x (1 - {num(stop_param)}%) = ${num(raw)}"
    elif stop_rule == "atr":
        if atr is None:
            raise PlanError("an atr stop needs the session's bars")
        a = D(round(atr, 6))
        raw = e - stop_param * a
        label = f"{num(stop_param)} x ATR({atr_bars:d}) under the entry"
        detail = "ATR ${} over the {:d} bars to the entry{}".format(
            num(a.quantize(Decimal("0.0001"))),
            atr_bars,
            " (fewer than 14 so far)" if atr_bars < ATR_BARS else "",
        )
    else:
        raise PlanError(f"unknown stop rule {stop_rule!r}")
    stop = floor_cents(raw)
    if stop != D(raw):
        detail = detail + ", rounded down" if detail else f"${num(raw)} rounded down"
    if stop >= e:
        raise PlanError(
            f"the stop {money(stop)} ({label}) is at or above the entry {money(e)}: a long's stop goes under the entry"
        )
    if stop <= 0:
        raise PlanError(f"the stop works out to {money(stop)}: pick a stop above $0")
    risk = e - stop
    floor_risk = e * MIN_RISK_PCT / 100
    if risk < floor_risk:
        raise PlanError(
            f"the stop is {money(risk)} under the entry, less than 0.05% of the price ({money(floor_risk.quantize(CENT, rounding=ROUND_HALF_UP))} on {money(e)}): too tight to "
            "survive the spread, normal wiggle would stop you out. Widen it."
        )
    if target_rule == "r":
        target = cents(e + target_param * risk)
        t_label = r_label(target_param)
    else:
        target = cents(target_param)
        t_label = None
    if target <= e:
        raise PlanError(
            f"the target {money(target)} is at or below the entry {money(e)}: a long's target goes above it"
        )
    rr = ((target - e) / risk).quantize(CENT, rounding=ROUND_HALF_UP)
    if t_label is None:
        t_label = f"your price ({ratio(rr)}R)"
    return {
        "entry": e,
        "stop": stop,
        "stop_label": label,
        "stop_detail": detail,
        "target": target,
        "target_r": target_param if target_rule == "r" else rr,
        "target_label": t_label,
        "risk": risk,
        "reward_risk": rr,
    }


# ---------------------------------------------------------------- bars for ATR (same reader as intraday-entry-timer)


def _open_url(url, timeout=20):
    req = urllib.request.Request(url, headers={"User-Agent": UA, "Accept": "application/json"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read().decode("utf-8", "replace")


def _sleep(seconds):
    time.sleep(seconds)


def yahoo_get(path):
    """query2 first, query1 on 429 or 5xx; one retry after a pause on 429."""
    last = "no answer"
    for host in HOSTS:
        url = f"https://{host}.finance.yahoo.com{path}"
        for attempt in (0, 1):
            try:
                return _open_url(url)
            except urllib.error.HTTPError as e:
                code, body = e.code, None
                try:
                    if code == 404:  # Yahoo says why in the body: an unknown ticker
                        body = e.read().decode("utf-8", "replace")
                except Exception:
                    body = None
                finally:
                    e.close()
                if code == 404:
                    if body:
                        return body
                    raise PlanError("Yahoo has no chart at {} (HTTP 404)".format(url.split("?")[0]))
                last = f"HTTP {code:d}"
                if code == 429 and attempt == 0:
                    _sleep(BACKOFF)
                    continue
                if code == 429 or code >= 500:
                    break
                raise PlanError("Yahoo answered HTTP {:d} for {}".format(code, url.split("?")[0]))
            except urllib.error.URLError as e:
                last = f"could not connect: {e.reason}"
                break
            except OSError as e:
                last = f"network error: {e}"
                break
    raise PlanError(
        f"Yahoo did not answer ({last} on query2 and query1): wait a minute and try again"
    )


def read_text(path):
    if path.endswith(".gz"):
        with gzip.open(path, "rt", encoding="utf-8") as fh:
            return fh.read()
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def load_chart(sym, interval, day, offline=None):
    ysym = sym.upper().replace(".", "-")
    if offline:
        path = offline
        if os.path.isdir(offline):
            path = os.path.join(offline, ysym + ".json")
            if not os.path.exists(path):
                path += ".gz"
        if not os.path.exists(path):
            raise PlanError(f"no offline file {path}")
        try:
            text = read_text(path)
        except (OSError, ValueError) as e:
            raise PlanError(f"could not read {path}: {e}")
    else:
        back = (to_eastern(utc_now()).date() - day).days
        rng = "1d" if back <= 0 else "5d" if back <= 6 else "1mo" if back <= 28 else "60d"
        if interval == "1m" and back > 6:
            raise PlanError("Yahoo keeps 1-minute bars for about a week")
        text = yahoo_get(f"/v8/finance/chart/{ysym}?range={rng}&interval={interval}")
    try:
        data = json.loads(text)
        res = data["chart"]["result"]
    except (ValueError, KeyError, TypeError):
        raise PlanError(f"Yahoo returned something unexpected for {sym}")
    if not res:
        err = (data.get("chart") or {}).get("error") or {}
        raise PlanError(
            "Yahoo has no data for {}: {}".format(sym, err.get("description") or "unknown ticker")
        )
    r = res[0] or {}
    meta = r.get("meta") or {}
    if str(meta.get("symbol") or ysym).upper() != ysym:
        raise PlanError("the chart file holds {}, not {}".format(meta.get("symbol"), sym))
    q = ((r.get("indicators") or {}).get("quote") or [{}])[0] or {}

    def at(key, i):
        arr = q.get(key) or []
        return arr[i] if i < len(arr) else None

    bars = []
    for i, t in enumerate(r.get("timestamp") or []):
        c = at("close", i)
        if t is None or c is None:
            continue
        h, lo = at("high", i), at("low", i)
        bars.append(
            {
                "t": int(t),
                "h": float(c if h is None else h),
                "l": float(c if lo is None else lo),
                "c": float(c),
            }
        )
    return {"bars": bars, "data_time": meta.get("regularMarketTime")}


def session_bars(chart, day, interval, upto_slot=None, now_utc=None):
    """Closed, on-grid bars of one New York session, oldest first (the live tick is dropped)."""
    step = INTERVALS[interval]
    s = session(day)
    if not s:
        return []
    open_dt = datetime.datetime.combine(day, s[0])
    close_dt = datetime.datetime.combine(day, s[1])
    if now_utc is None and chart.get("data_time"):
        now_utc = utc_of(chart["data_time"])
    local = to_eastern(now_utc) if now_utc else None
    out = {}
    for b in chart["bars"]:
        if b["t"] % step:
            continue
        et = to_eastern(utc_of(b["t"]))
        if et.date() != day or not (open_dt <= et < close_dt):
            continue
        if local and et + datetime.timedelta(seconds=step) > local:
            continue
        slot = int((et - open_dt).total_seconds()) // step
        if upto_slot is not None and slot > upto_slot:
            continue
        out[slot] = b
    return [out[k] for k in sorted(out)]


def atr_of(bars, n=ATR_BARS):
    """Average true range of the last n bars (all of them if fewer). The first
    bar of the session uses its own high - low (no overnight gap)."""
    trs, prev = [], None
    for b in bars:
        tr = b["h"] - b["l"]
        if prev is not None:
            tr = max(tr, abs(b["h"] - prev), abs(b["l"] - prev))
        trs.append(tr)
        prev = b["c"]
    use = trs[-n:]
    return sum(use) / len(use), len(use)


