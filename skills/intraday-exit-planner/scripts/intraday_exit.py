#!/usr/bin/env python3
"""intraday-exit-planner: sets the stop and the target BEFORE you enter, so you
know when to get out. Long side only. It never places an order.

    python3 intraday_exit.py plan                        # newest entry report: or-mid stop, 2R target
    python3 intraday_exit.py plan --stop or-mid --target 1R  # the TSLA example: stop 358.32, target 370.04
    python3 intraday_exit.py plan --symbol TSLA --entry 364.18 --or-high 362.18 --or-low 354.47
    python3 intraday_exit.py plan --stop atr:1.5 --offline TSLA.json # ATR needs the session's bars
    python3 intraday_exit.py plan --symbol NVDA --entry 190.25 --setup level --stop pct:1
    python3 intraday_exit.py show                                    # the newest exit plan report

Stops (a long's stop rounds DOWN to the cent, away from the entry):
  or-mid     the opening-range midpoint (the default for an orb entry)
  or-low     the opening-range low
  price:X    your price
  pct:X      X percent under the entry
  atr:K      K times the 14-bar ATR under the entry, on the session's bars up
             to the entry bar (--offline FILE or Yahoo). With fewer than 14
             bars by then it averages all of them and says so.
  A level setup has no opening-range default: give a stop.

Targets (round half up to the cent):
  2R (default), 1R, 1.5R ...   entry + R x risk, where risk = entry - stop
  price:X                      your price

Refused, with the reason: a stop at or above the entry, a target at or below
it, a risk under 0.05% of the price (too tight to survive the spread), an
entry report that has not triggered (unless you give --entry), a short (longs
only).

Flat by 15:55 New York time by default: out by then, win or lose. On an early
close it moves up with the close (12:55 before a 1:00 p.m. close); --flat-by
HH:MM sets an exact time instead. --min-reward-risk (default 1.0) only warns
here. position-sizer --intraday-plan refuses a plan under the floor.

Reports: plan writes reports/intraday_exit_plan_<TICKER>_<date>.json and .md
(the input of intraday-time-machine, position-sizer --intraday-plan and
intraday-alerts) unless --no-write.

A stop is a plan, not a guarantee: a gap or a fast market can fill past it.
Exit codes: plan 0 = a plan, 1 = refused or an error. show 0 = a plan exists.
"""

