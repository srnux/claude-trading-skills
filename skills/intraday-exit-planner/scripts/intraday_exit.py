def read_json(path, what):
    if not path or not os.path.exists(path):
        raise PlanError(f"no {what} at {path}")
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh)
    except ValueError as e:
        raise PlanError(f"{path} is not valid JSON: {e}")


def plan_rules(min_reward_risk=None):
    """The defaults this planner applies: flat by 15:55 and a 1.0 reward:risk warning floor."""
    cfg = dict(DEFAULTS)
    if min_reward_risk is not None:
        cfg["min_reward_risk"] = min_reward_risk
    return cfg


def latest_report(output_dir, prefix):
    """The newest <output_dir>/<prefix>*.json by modification time, or None."""
    paths = [p for p in glob.glob(os.path.join(output_dir, prefix + "*.json")) if os.path.isfile(p)]
    return max(paths, key=os.path.getmtime) if paths else None


def resolve_flat_by(day, explicit, cfg, entry_time):
    """(HH:MM, note). The config's flat-by moves up with a 1:00 p.m. early close."""
    t = parse_hhmm(
        explicit or cfg.get("flat_by") or DEFAULTS["flat_by"],
        "--flat-by" if explicit else "flat_by",
    )
    note = ""
    s = session(day) if day else None
    if s:
        close_dt = datetime.datetime.combine(day, s[1])
        at = datetime.datetime.combine(day, t)
        if at >= close_dt:
            if explicit:
                raise PlanError(f"--flat-by {hm(t)} is at or after the {ampm(s[1])} close on {day}")
            moved = at - (datetime.datetime.combine(day, CLOSE) - close_dt)
            if moved.time() <= OPEN:
                raise PlanError(f"flat_by {hm(t)} in the config is at or after the close")
            t = moved.time()
            note = f"moved up for the {early_close(day)}"
    if entry_time and entry_time >= t:
        raise PlanError(
            f"the entry at {ampm(entry_time)} is at or after your flat-by {hm(t)}: there is no time left to hold it"
        )
    return hm(t), note


def gather(a):
    """The entry facts, from an intraday-entry-timer report or the flags."""
    if a.symbol and a.from_path:
        raise PlanError("use --from or --symbol, not both")
    if a.side in ("sell", "short"):
        raise PlanError(
            "intraday plans are longs only: no stops above a short entry. Plan a buy instead."
        )
    if a.symbol:
        if a.entry is None:
            raise PlanError("--symbol needs --entry PRICE")
        if (a.or_high is None) != (a.or_low is None):
            raise PlanError("give both --or-high and --or-low, or neither")
        info = {
            "symbol": a.symbol.upper(),
            "entry": a.entry,
            "setup": a.setup or ("orb" if a.or_high is not None else "level"),
            "date": a.date,
            "entry_time": a.time,
            "entry_bar": a.entry_bar,
            "interval": a.interval or "5m",
            "or_high": a.or_high,
            "or_low": a.or_low,
            "or_minutes": a.or_minutes,
            "source": "flags",
        }
    else:
        path = a.from_path or latest_report(a.output_dir, "intraday_entry_")
        if not path:
            raise PlanError(
                f"no intraday-entry-timer report in {a.output_dir}: run intraday-entry-timer first, "
                "or give --symbol and --entry"
            )
        doc = read_json(
            path, "entry (run intraday-entry-timer first, or give --symbol and --entry)"
        )
        if str(doc.get("side") or "buy").lower() not in ("buy", "long"):
            raise PlanError(
                "{} is a {}: intraday plans are longs only".format(path, doc.get("side"))
            )
        if doc.get("status") != "triggered" and a.entry is None:
            raise PlanError(
                "{} says {} is {}, not triggered: plan once it triggers, or give --entry PRICE to plan ahead".format(
                    path, doc.get("symbol"), doc.get("status") or "unknown"
                )
            )
        orr = doc.get("opening_range") or {}
        info = {
            "symbol": str(doc.get("symbol") or "").upper(),
            "entry": a.entry if a.entry is not None else doc.get("price"),
            "setup": a.setup or doc.get("setup") or "orb",
            "date": a.date or doc.get("date"),
            "entry_time": a.time or (doc.get("time") if a.entry is None else None),
            "entry_bar": a.entry_bar
            if a.entry_bar is not None
            else (doc.get("bar_index") if a.entry is None else None),
            "interval": a.interval or doc.get("interval") or "5m",
            "or_high": a.or_high if a.or_high is not None else orr.get("high"),
            "or_low": a.or_low if a.or_low is not None else orr.get("low"),
            "or_minutes": orr.get("minutes") or a.or_minutes,
            "source": path,
        }
        if not info["symbol"] or info["entry"] is None:
            raise PlanError(f"{path} has no symbol or price")
    if info["interval"] not in INTERVALS:
        raise PlanError("interval is 5m or 1m")
    return info


def build_plan(a, now_utc):
    info = gather(a)
    cfg = plan_rules(a.min_reward_risk)
    stop_text = a.stop
    if not stop_text:
        if info["setup"] != "orb":
            raise PlanError(
                "a {} setup has no opening-range stop to default to: give --stop price:X, pct:X or atr:K".format(
                    info["setup"]
                )
            )
        stop_text = "or-mid"
    stop_rule, stop_param = parse_stop(stop_text)
    target_rule, target_param = parse_target(a.target or "2R")
    day = None
    if info["date"]:
        try:
            day = datetime.date.fromisoformat(str(info["date"]))
        except ValueError:
            raise PlanError("date wants YYYY-MM-DD, not {!r}".format(info["date"]))
    else:
        day = to_eastern(now_utc).date()
    entry_time = parse_clock(info["entry_time"], "the entry time") if info["entry_time"] else None
    atr = atr_n = None
    if stop_rule == "atr":
        chart = load_chart(info["symbol"], info["interval"], day, a.offline)
        bars = session_bars(
            chart, day, info["interval"], info["entry_bar"], parse_now(a.now) if a.now else None
        )
        if len(bars) < 3:
            raise PlanError(
                "an atr stop needs at least 3 closed {} bars of {} on {} by the entry; found {:d}".format(
                    info["interval"], info["symbol"], day, len(bars)
                )
            )
        atr, atr_n = atr_of(bars)
    c = compute(
        info["entry"],
        stop_rule,
        stop_param,
        target_rule,
        target_param,
        info["or_high"],
        info["or_low"],
        atr,
        atr_n,
    )
    flat_by, flat_note = resolve_flat_by(day, a.flat_by, cfg, entry_time)
    orr = None
    if info["or_high"] is not None and info["or_low"] is not None:
        orr = {
            "high": float(cents(info["or_high"])),
            "low": float(cents(info["or_low"])),
            "minutes": int(info["or_minutes"] or 15),
        }
    plan = {
        "created_by": "intraday-exit-planner",
        "symbol": info["symbol"],
        "side": "buy",
        "date": day.isoformat(),
        "setup": info["setup"],
        "entry": float(c["entry"]),
        "entry_time": ampm(entry_time) if entry_time else None,
        "entry_bar": info["entry_bar"],
        "interval": info["interval"],
        "opening_range": orr,
        "stop": float(c["stop"]),
        "stop_rule": stop_rule,
        "stop_label": c["stop_label"],
        "target": float(c["target"]),
        "target_r": float(c["target_r"]),
        "target_label": c["target_label"],
        "risk_per_share": float(c["risk"]),
        "reward_risk": float(c["reward_risk"]),
        "flat_by": flat_by,
        "stop_detail": c["stop_detail"],
        "created_at": now_utc.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "note": NOTE,
    }
    if atr is not None:
        plan["atr"] = round(atr, 4)
        plan["atr_bars"] = atr_n
    warnings = []
    if flat_note:
        warnings.append(f"Flat-by {flat_by}: {flat_note}.")
    mrr = cfg.get("min_reward_risk")
    try:
        if mrr is not None and c["reward_risk"] < D(mrr):
            warnings.append(
                "Reward:risk {} is under your min_reward_risk {} from --min-reward-risk: position-sizer --intraday-plan refuses it.".format(
                    ratio(c["reward_risk"]), num(D(mrr))
                )
            )
    except PlanError:
        pass
    today = to_eastern(now_utc).date()
    if day != today:
        warnings.append(f"This plan is for {day.isoformat()}, not today ({today.isoformat()}).")
    return plan, warnings


def describe(plan):
    day = datetime.date.fromisoformat(plan["date"])
    setup = {"orb": "opening-range breakout", "level": "close above a level"}.get(
        plan["setup"], plan["setup"]
    )
    e = D(plan["entry"])
    risk = D(plan["risk_per_share"])
    pct = (risk / e * 100).quantize(CENT, rounding=ROUND_HALF_UP)
    when = ""
    if plan.get("entry_time"):
        when = " at {}".format(plan["entry_time"])
        if plan.get("entry_bar") is not None:
            when += " (bar {:d})".format(plan["entry_bar"])
    out = [
        "Exit plan: {} long, {}, {} on {} bars".format(
            plan["symbol"],
            day.strftime("%a %Y-%m-%d"),
            setup,
            "5-minute" if plan["interval"] == "5m" else "1-minute",
        )
    ]
    out.append("  Entry         {}{}".format(money(plan["entry"]), when))
    out.append(
        "  Stop          {}  {}{}".format(
            money(plan["stop"]),
            plan["stop_label"],
            (": " + plan["stop_detail"]) if plan.get("stop_detail") else "",
        )
    )
    out.append("  Target        {}  {}".format(money(plan["target"]), plan["target_label"]))
    out.append("  Risk a share  {} ({}% of the entry)".format(money(plan["risk_per_share"]), pct))
    out.append("  Reward:risk   {}".format(ratio(plan["reward_risk"])))
    out.append("  Flat by       {} ET, win or lose: no overnight hold".format(plan["flat_by"]))
    out.append(
        "Set before the entry. If price hits the stop, you are out; never move it further away."
    )
    out.append(NOTE)
    return out


def write_plan_report(output_dir, plan, warnings):
    """reports/intraday_exit_plan_<TICKER>_<date>.json + .md. Returns (json_path, md_path)."""
    stem = "intraday_exit_plan_{}_{}".format(plan["symbol"].replace(".", "-"), plan["date"])
    os.makedirs(output_dir, exist_ok=True)
    json_path = os.path.join(output_dir, stem + ".json")
    md_path = os.path.join(output_dir, stem + ".md")
    with open(json_path, "w", encoding="utf-8") as fh:
        json.dump(plan, fh, indent=2)
        fh.write("\n")
    lines = (
        ["# Intraday Exit Plan: {} {}".format(plan["symbol"], plan["date"]), "", "```text"]
        + describe(plan)
        + ["```"]
    )
    if warnings:
        lines += ["", "## Notes", ""] + ["- " + w for w in warnings]
    lines += [
        "",
        "Next: intraday-time-machine replays this plan, then position-sizer --intraday-plan sizes it. "
        "Nothing was placed.",
    ]
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    return json_path, md_path


def cmd_plan(a):
    now = parse_now(a.now)
    plan, warnings = build_plan(a, now)
    written = None
    if not a.no_write:
        written = write_plan_report(a.output_dir, plan, warnings)
    if a.json:
        print(json.dumps(dict(plan, warnings=warnings), indent=2))
        return 0
    for line in describe(plan):
        print(line)
    for w in warnings:
        print("Note: " + w)
    if written:
        print("Wrote {} and {}.".format(*written))
    print(
        "Next: intraday-time-machine replays it, then position-sizer --intraday-plan sizes it to your max loss. "
        "Nothing was placed."
    )
    return 0


def cmd_show(a):
    a.plan = a.plan or latest_report(a.output_dir, "intraday_exit_plan_")
    if not a.plan or not os.path.exists(a.plan):
        print("No plan at %s yet. Make one: intraday_exit.py plan" % (a.plan or a.output_dir))
        return 1
    plan = read_json(a.plan, "plan")
    for k in (
        "symbol",
        "date",
        "entry",
        "stop",
        "target",
        "risk_per_share",
        "reward_risk",
        "flat_by",
    ):
        if plan.get(k) is None:
            raise PlanError(
                f"{a.plan} is missing {k!r}: make a new plan with intraday_exit.py plan"
            )
    if a.json:
        print(json.dumps(plan, indent=2))
        return 0
    for line in describe(
        dict({"setup": "orb", "interval": "5m", "stop_label": "", "target_label": ""}, **plan)
    ):
        print(line)
    today = to_eastern(parse_now(a.now)).date().isoformat()
    if plan["date"] != today:
        print("Note: this plan is for {}, not today ({}).".format(plan["date"], today))
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(
        description="intraday-exit-planner: the stop and target before the entry."
    )
    sub = ap.add_subparsers(dest="cmd")
    p = sub.add_parser("plan", help="set the stop and target")
    p.add_argument(
        "--from",
        dest="from_path",
        metavar="PATH",
        help="entry report to plan from (default: the newest reports/intraday_entry_*.json)",
    )
    p.add_argument("--symbol")
    p.add_argument("--entry", type=float, help="entry price (or a plan-ahead price with --from)")
    p.add_argument("--or-high", type=float)
    p.add_argument("--or-low", type=float)
    p.add_argument("--or-minutes", type=int, default=15)
    p.add_argument("--setup", choices=["orb", "level"])
    p.add_argument("--date", help="session date YYYY-MM-DD (default: the entry's, or today)")
    p.add_argument("--time", help="entry time, e.g. 10:15 AM")
    p.add_argument("--entry-bar", type=int)
    p.add_argument("--interval", choices=["5m", "1m"])
    p.add_argument(
        "--side",
        default="buy",
        choices=["buy", "long", "sell", "short"],
        help="buy only (longs only)",
    )
    p.add_argument("--stop", help="or-mid (orb default), or-low, price:X, pct:X, atr:K")
    p.add_argument("--target", help="2R (default), 1R, 1.5R, price:X")
    p.add_argument("--flat-by", help="HH:MM New York (default: config flat_by, 15:55)")
    p.add_argument(
        "--min-reward-risk", type=float, help="warn under this reward:risk (default 1.0)"
    )
    p.add_argument(
        "--output-dir", default=DEFAULT_OUTPUT_DIR, help="reports folder (default reports/)"
    )
    p.add_argument("--offline", metavar="PATH", help="saved Yahoo chart JSON for an atr stop")
    p.add_argument("--now", help='pretend it is this New York time, e.g. "2026-10-19 10:15"')
    p.add_argument("--no-write", action="store_true", help="do not write the plan report")
    p.add_argument("--json", action="store_true")
    p = sub.add_parser("show", help="print the current plan")
    p.add_argument(
        "--plan", help="plan report (default: the newest reports/intraday_exit_plan_*.json)"
    )
    p.add_argument("--output-dir", default=DEFAULT_OUTPUT_DIR)
    p.add_argument("--now")
    p.add_argument("--json", action="store_true")
    a = ap.parse_args(argv)
    if not a.cmd:
        ap.print_help()
        return 1
    try:
        return {"plan": cmd_plan, "show": cmd_show}[a.cmd](a)
    except CalendarMissing as e:
        print(f"intraday_exit.py: {e}", file=sys.stderr)
        return 2
    except PlanError as e:
        print(f"intraday_exit.py: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
